def render_fallback_procedural_stem(stem_path: Path, clip_info: Dict[str, Any]) -> Path:
    """
    Emergency procedural animated stem (only if Vertex AI Veo is unreachable offline).
    Generates a 24fps 8-second MP4 with animated explosions, tracer streaks, and radar scanlines.
    """
    tmp_frames_dir = STEMS_DIR / f"tmp_{clip_info['slug']}"
    tmp_frames_dir.mkdir(parents=True, exist_ok=True)
    rng = random.Random(hash(clip_info["slug"]))
    w, h = 640, 360
    for f_idx in range(96):
        t = f_idx / 24.0
        img = Image.new("RGB", (w, h), (8, 14, 24))
        draw = ImageDraw.Draw(img)
        # Horizon glow
        for y in range(h):
            r = int(12 + 45 * math.exp(-((y - h * 0.68) ** 2) / 2800.0))
            g = int(16 + 22 * math.exp(-((y - h * 0.68) ** 2) / 2800.0))
            b = int(28 + 30 * (1.0 - y / h))
            draw.line([(0, y), (w, y)], fill=(min(255, r), min(255, g), min(255, b)))
        # Animated explosions & missile arcs
        for m in range(7):
            mx = int((w * (0.15 + 0.12 * m) + f_idx * (3 + m)) % w)
            my = int(h * 0.72 - ((f_idx * (5 + m * 2) + m * 37) % int(h * 0.62)))
            draw.line([(mx - 12, my + 28), (mx, my)], fill=(255, 190, 80), width=3)
            rad = int(8 + 26 * abs(math.sin(t * 3.0 + m)))
            draw.ellipse([mx - rad, my - rad, mx + rad, my + rad], fill=(255, 110, 30), outline=(255, 240, 180), width=2)
        img.save(tmp_frames_dir / f"f_{f_idx:03d}.jpg", quality=88)

    cmd = [
        FFMPEG_PATH, "-y",
        "-framerate", "24",
        "-i", str(tmp_frames_dir / "f_%03d.jpg"),
        "-stream_loop", "1",
        "-t", "8",
        "-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p",
        str(stem_path)
    ]
    subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
    shutil.rmtree(tmp_frames_dir, ignore_errors=True)
    return stem_path


def process_single_clip(clip_info: Dict[str, Any], api_key: str) -> Dict[str, Any]:
    """Full pipeline for one war news video clip: Gemini Copy -> Veo 3.1 Stem -> Audio -> FFmpeg MP4/OGV/Filmstrip."""
    slug = clip_info["slug"]
    out_mp4 = NEWS_OUT_DIR / f"{slug}.mp4"
    out_ogv = NEWS_OUT_DIR / f"{slug}.ogv"
    out_sheet = NEWS_OUT_DIR / f"{slug}_sheet.jpg"
    out_thumb = NEWS_OUT_DIR / f"{slug}_thumb.jpg"
    overlay_png = OVERLAYS_DIR / f"{slug}_overlay.png"
    wav_path = OVERLAYS_DIR / f"{slug}_audio.wav"

    # 1. Enrich copy with Gemini 2.5 Flash
    copy_data = enrich_news_copy_with_gemini(api_key, clip_info)

    # 2. Obtain Google Veo 3.1 Fast 8-second HD stem
    stem_path = generate_veo_stem(clip_info)
    is_veo_ai = True
    if stem_path is None or not stem_path.exists():
        is_veo_ai = False
        stem_path = STEMS_DIR / f"{slug}_veo.mp4"
        render_fallback_procedural_stem(stem_path, clip_info)

    # 3. Synthesize broadcast audio WAV & TV Chyron PNG
    synthesize_broadcast_audio_wav(wav_path, clip_info["sound_profile"], duration_sec=8.0)
    create_broadcast_overlay_png(
        overlay_png,
        network=clip_info["network"],
        category=clip_info["category"],
        defcon=int(clip_info["default_defcon"]),
        headline=copy_data["headline"],
        sub_chyron=copy_data["sub_chyron"],
        correspondent=copy_data["correspondent"],
    )

    # 4. Composite Final Broadcast MP4 (1280x720 H.264 + AAC)
    filter_mp4 = "[0:v]scale=1280:720[v_bg];[v_bg][1:v]overlay=0:0[v_out]"
    cmd_mp4 = [
        FFMPEG_PATH, "-y",
        "-i", str(stem_path),
        "-i", str(overlay_png),
        "-i", str(wav_path),
        "-filter_complex", filter_mp4,
        "-map", "[v_out]",
        "-map", "2:a",
        "-c:v", "libx264", "-preset", "veryfast", "-crf", "22", "-pix_fmt", "yuv420p",
        "-c:a", "aac", "-b:a", "192k",
        "-shortest",
        str(out_mp4),
    ]
    subprocess.run(cmd_mp4, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)

    # 5. Encode Native Godot 4.7 Ogg Theora + Vorbis (.ogv) for VideoStreamPlayer
    cmd_ogv = [
        FFMPEG_PATH, "-y",
        "-i", str(out_mp4),
        "-vf", "scale=640:360",
        "-c:v", "libtheora", "-q:v", "7",
        "-c:a", "libvorbis", "-q:a", "4",
        str(out_ogv),
    ]
    subprocess.run(cmd_ogv, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)

    # 6. Extract 24-frame (6x4 grid, 320x180 per frame = 1920x720) Filmstrip Contact Sheet + 640x360 Thumbnail
    cmd_sheet = [
        FFMPEG_PATH, "-y",
        "-i", str(out_mp4),
        "-vf", "fps=3,scale=320:180,tile=6x4",
        "-frames:v", "1",
        "-q:v", "3",
        str(out_sheet),
    ]
    subprocess.run(cmd_sheet, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)

    cmd_thumb = [
        FFMPEG_PATH, "-y",
        "-ss", "00:00:02.50",
        "-i", str(out_mp4),
        "-vf", "scale=640:360",
        "-frames:v", "1",
        "-q:v", "3",
        str(out_thumb),
    ]
    subprocess.run(cmd_thumb, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)

    print(
        f"[BroadcastReady] {slug}: MP4={out_mp4.stat().st_size // 1024}KB | "
        f"OGV={out_ogv.stat().st_size // 1024}KB | Sheet={out_sheet.stat().st_size // 1024}KB | VeoAI={is_veo_ai}"
    )

    return {
        "slug": slug,
        "event_trigger": clip_info["event_trigger"],
        "network": clip_info["network"],
        "category": clip_info["category"],
        "defcon": int(clip_info["default_defcon"]),
        "headline": copy_data["headline"],
        "sub_chyron": copy_data["sub_chyron"],
        "correspondent": copy_data["correspondent"],
        "mp4_res_path": f"res://assets/videos/news/{slug}.mp4",
        "ogv_res_path": f"res://assets/videos/news/{slug}.ogv",
        "sheet_res_path": f"res://assets/videos/news/{slug}_sheet.jpg",
        "thumb_res_path": f"res://assets/videos/news/{slug}_thumb.jpg",
        "sheet_cols": 6,
        "sheet_rows": 4,
        "sheet_frames": 24,
        "duration_sec": 8.0,
        "is_veo_generated": is_veo_ai,
    }


