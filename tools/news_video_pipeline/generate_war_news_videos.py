def load_credentials() -> str:
    """Loads GEMINI_API_KEY and GOOGLE_APPLICATION_CREDENTIALS from local or villeraengine config."""
    env_candidates = [
        ROOT_DIR / ".env",
        VILLERA_DIR / ".env",
        VILLERA_DIR / "server" / ".env",
        Path.home() / ".env",
    ]
    for env_path in env_candidates:
        if env_path.exists():
            try:
                for line in env_path.read_text(encoding="utf-8").splitlines():
                    line = line.strip()
                    if line and not line.startswith("#") and "=" in line:
                        k, v = line.split("=", 1)
                        k = k.strip()
                        v = v.strip().strip("'\"")
                        if k and k not in os.environ:
                            os.environ[k] = v
            except Exception as e:
                print(f"[Credentials] Notice reading {env_path}: {e}")

    gcp_candidates = [
        ROOT_DIR / "gcp-key.json",
        ROOT_DIR / "tools" / "news_video_pipeline" / "gcp-key.json",
        VILLERA_DIR / "server" / "gcp-key.json",
    ]
    for gcp_path in gcp_candidates:
        if gcp_path.exists() and "GOOGLE_APPLICATION_CREDENTIALS" not in os.environ:
            os.environ["GOOGLE_APPLICATION_CREDENTIALS"] = str(gcp_path.resolve())
            break

    return (os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY") or "").strip()


