def enrich_news_copy_with_gemini(api_key: str, clip_info: Dict[str, Any]) -> Dict[str, str]:
    """Uses Google Gemini 2.5 Flash to generate punchy, realistic broadcast news copy for the clip."""
    result = {
        "headline": clip_info["default_headline"],
        "sub_chyron": clip_info["default_sub_chyron"],
        "correspondent": clip_info["default_correspondent"],
    }
    if not api_key:
        return result

    try:
        from google import genai
        from google.genai import types

        client = genai.Client(api_key=api_key, http_options={"timeout": 15000})
        prompt = f"""
You are the Executive Producer of a 24-hour global breaking news network (like CNN International / BBC World / Al Jazeera) in the year 2028.
Generate a realistic, dramatic television breaking news lower-third chyron package for this military event:
Event Category: {clip_info['category']}
Default Headline: {clip_info['default_headline']}
Context: {clip_info['default_sub_chyron']}

Return STRICTLY a JSON object with keys:
- "headline": ALL CAPS breaking news headline (max 82 characters, punchy, urgent)
- "sub_chyron": Secondary ticker line with realistic military/geopolitical detail (max 135 characters)
- "correspondent": Name and title of the live field correspondent
"""
        config = types.GenerateContentConfig(
            temperature=0.75,
            response_mime_type="application/json",
        )
        resp = client.models.generate_content(
            model="gemini-2.5-flash-lite",
            contents=prompt,
            config=config,
        )
        if resp and resp.text:
            data = json.loads(resp.text.strip())
            if isinstance(data, dict):
                if data.get("headline"):
                    result["headline"] = str(data["headline"]).upper()[:92]
                if data.get("sub_chyron"):
                    result["sub_chyron"] = str(data["sub_chyron"])[:155]
                if data.get("correspondent"):
                    result["correspondent"] = str(data["correspondent"])[:64]
    except Exception as e:
        print(f"[GeminiNews] Notice for {clip_info['slug']}: {e}")

    return result


def generate_veo_stem(clip_info: Dict[str, Any]) -> Optional[Path]:
    """Generates or reuses an 8-second 16:9 HD video stem via Google Veo 3.1 Fast on Vertex AI."""
    slug = clip_info["slug"]
    stem_path = STEMS_DIR / f"{slug}_veo.mp4"
    if stem_path.exists() and stem_path.stat().st_size > 100000:
        print(f"[Veo 3.1 Fast] Using cached Veo stem: {stem_path.name} ({stem_path.stat().st_size // 1024} KB)")
        return stem_path

    try:
        from google import genai
        from google.genai import types

        client = genai.Client(vertexai=True, project="yellowbeacon-telemetry", location="us-central1")
        for attempt_idx, prompt_text in enumerate([clip_info["veo_prompt"], clip_info["fallback_veo_prompt"]]):
            try:
                print(f"[Veo 3.1 Fast] Launching generation for '{slug}' (attempt {attempt_idx + 1})...")
                source = types.GenerateVideosSource(prompt=prompt_text)
                config = types.GenerateVideosConfig(
                    duration_seconds=8,
                    aspect_ratio="16:9",
                    number_of_videos=1,
                    fps=24,
                )
                operation = client.models.generate_videos(
                    model="publishers/google/models/veo-3.1-fast-generate-001",
                    source=source,
                    config=config,
                )
                polls = 0
                while not operation.done and polls < 40:
                    time.sleep(3)
                    operation = client.operations.get(operation)
                    polls += 1

                if operation.done and hasattr(operation, "response") and operation.response and operation.response.generated_videos:
                    gen_video = operation.response.generated_videos[0].video
                    if gen_video.video_bytes:
                        stem_path.write_bytes(gen_video.video_bytes)
                        print(f"[Veo 3.1 Fast] [OK] Saved {stem_path.name} ({len(gen_video.video_bytes) // 1024} KB)")
                        return stem_path
                    elif gen_video.uri:
                        import urllib.request
                        urllib.request.urlretrieve(gen_video.uri, str(stem_path))
                        print(f"[Veo 3.1 Fast] [OK] Downloaded {stem_path.name}")
                        return stem_path
                else:
                    err_info = getattr(operation, "error", "Filtered or empty response")
                    print(f"[Veo 3.1 Fast] Notice on attempt {attempt_idx + 1} for {slug}: {err_info}")
            except Exception as inner_e:
                print(f"[Veo 3.1 Fast] Exception on attempt {attempt_idx + 1} for {slug}: {inner_e}")
                time.sleep(2)
    except Exception as e:
        print(f"[Veo 3.1 Fast] Client init error for {slug}: {e}")

    return None


def synthesize_broadcast_audio_wav(wav_path: Path, profile: str, duration_sec: float = 8.0) -> Path:
    """
    Synthesizes an 8-second stereo broadcast audio track combining:
    - Breaking news urgent teletype/stinger pulse
    - Deep physical explosion shockwave booms, supersonic missile Doppler whooshes, or klaxon sirens
    """
    sr = 22050
    total_samples = int(sr * duration_sec)
    rng = random.Random(hash(profile))

    # Pre-generate noise buffer for explosions/jet roar
    noise_buf = [rng.uniform(-1.0, 1.0) for _ in range(sr)]

    # Explosion trigger times (in seconds)
    if profile in ("nuclear_blast", "orbital_rod_impact"):
        boom_times = [0.6, 2.4, 5.0]
    elif profile in ("missile_barrage", "sam_intercept", "jet_airstrike", "naval_salvo", "urban_combat"):
        boom_times = [0.4, 1.5, 2.8, 4.1, 5.5, 6.8]
    else:
        boom_times = [0.8, 3.6, 6.2]

    lp_l = 0.0
    lp_r = 0.0
    frames = bytearray()

    for i in range(total_samples):
        t = i / sr
        sample_l = 0.0
        sample_r = 0.0

        # 1. Breaking News Urgent Sub-Pulse (subtle broadcast tension rhythm at 120 BPM)
        beat_phase = (t * 2.0) % 1.0
        if beat_phase < 0.18:
            env_pulse = math.sin((beat_phase / 0.18) * math.pi)
            # Warm newsroom bass pulse (110 Hz + 220 Hz)
            news_tone = (math.sin(2.0 * math.pi * 110.0 * t) * 0.14 + math.sin(2.0 * math.pi * 220.0 * t) * 0.06) * env_pulse
            sample_l += news_tone
            sample_r += news_tone

        # 2. Opening Broadcast News Stinger Chime (first 1.2s)
        if t < 1.2:
            note_hz = 587.33 if t < 0.3 else (659.25 if t < 0.6 else 880.0)
            stinger_env = math.exp(-t * 2.2) * 0.12
            chime = math.sin(2.0 * math.pi * note_hz * t) * stinger_env
            sample_l += chime * 0.9
            sample_r += chime * 1.1

        # 3. Missile Whoosh / Jet Pass / Siren depending on profile
        if profile in ("missile_barrage", "sam_intercept", "jet_airstrike", "naval_salvo"):
            # Supersonic Doppler whoosh every 2 seconds
            w_phase = (t % 2.0) / 2.0
            doppler_freq = 480.0 - 310.0 * w_phase
            w_env = math.sin(w_phase * math.pi) ** 2 * 0.18
            n_val = noise_buf[i % sr]
            whoosh = (n_val * 0.6 + math.sin(2.0 * math.pi * doppler_freq * t) * 0.4) * w_env
            pan = w_phase
            sample_l += whoosh * (1.0 - pan * 0.6)
            sample_r += whoosh * (0.4 + pan * 0.6)
        elif profile in ("cbrn_siren", "bunker_klaxon"):
            # Civil defense / bunker low-pass warning siren
            siren_hz = 320.0 + 110.0 * math.sin(2.0 * math.pi * 0.65 * t)
            siren = math.sin(2.0 * math.pi * siren_hz * t) * 0.14
            sample_l += siren
            sample_r += siren

        # 4. Deep Explosion Shockwave Booms
        for bt in boom_times:
            dt = t - bt
            if 0.0 <= dt < 1.8:
                boom_env = math.exp(-dt * (2.2 if profile == "nuclear_blast" else 3.8))
                sub_freq = 42.0 + 55.0 * math.exp(-dt * 8.0)
                rumble = noise_buf[(i * 3) % sr] * 0.55 + math.sin(2.0 * math.pi * sub_freq * dt) * 0.65
                amp = 0.52 if profile in ("nuclear_blast", "orbital_rod_impact") else 0.38
                sample_l += rumble * boom_env * amp
                sample_r += rumble * boom_env * amp * 0.95

        # 5. Warm low-pass filter to keep audio punchy and non-fatiguing
        alpha = 0.28
        lp_l = lp_l + alpha * (sample_l - lp_l)
        lp_r = lp_r + alpha * (sample_r - lp_r)

        out_l = int(max(-32000, min(32000, lp_l * 32000.0)))
        out_r = int(max(-32000, min(32000, lp_r * 32000.0)))
        frames += struct.pack("<hh", out_l, out_r)

    with wave.open(str(wav_path), "wb") as wf:
        wf.setnchannels(2)
        wf.setsampwidth(2)
        wf.setframerate(sr)
        wf.writeframes(bytes(frames))

    return wav_path


